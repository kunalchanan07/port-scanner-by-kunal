/**
 * Lightweight TCP Service Lookup Helper
 * Identifies common TCP service names for specific ports (e.g. 80 -> HTTP, 22 -> SSH, 3306 -> MySQL)
 * If port is not in predefined list, computes standard IANA classification gracefully.
 */
export function lookupTcpService(port: number): TcpServiceInfo {
  const numPort = Number(port);
  const known = COMMON_TCP_SERVICES[numPort];

  const portRange: TcpServiceInfo['portRange'] =
    numPort < 1024
      ? 'System (0-1023)'
      : numPort <= 49151
      ? 'Registered (1024-49151)'
      : 'Dynamic (49152-65535)';

  if (known) {
    return {
      port: numPort,
      portRange,
      isStandardKnown: true,
      ...known,
    };
  }

  // Graceful fallback for custom or unassigned port numbers
  const isPrivileged = numPort < 1024;
  return {
    port: numPort,
    name: `Port ${numPort}`,
    fullName: `Custom / Unassigned Service (${portRange})`,
    protocol: 'TCP',
    category: isPrivileged ? 'system' : 'other',
    categoryLabel: isPrivileged ? 'System Service' : 'Application Port',
    portRange,
    description: `Non-standard or custom TCP service listening on port ${numPort}.`,
    risk: isPrivileged ? 'medium' : 'low',
    securityNote: 'Verify whether this service is authorized to bind externally or should remain internal.',
    commonSoftware: ['Custom Application', 'Proprietary Daemon'],
    badgeColor: { bg: 'bg-slate-100', text: 'text-slate-700', border: 'border-slate-200' },
    isStandardKnown: false,
  };
}

/**
 * Backwards compatible getPortDetails wrapper
 */
export function getPortDetails(port: number) {
  const service = lookupTcpService(port);
  return {
    port: service.port,
    name: service.name,
    protocol: service.protocol,
    description: service.fullName + ' - ' + service.description,
    category: service.category,
    risk: service.risk,
    notes: service.securityNote,
    fullService: service,
  };
}

